def suggestions_for(user) -> list[str]:
    """Return department-aware Q&A suggestions while keeping admin broad."""
    if getattr(user, "is_admin", False):
        return list(ADMIN_SUGGESTIONS)
    return list(DEPARTMENT_SUGGESTIONS.get(getattr(user, "department", ""), DEFAULT_SUGGESTIONS))


def quick_questions_for(user, limit: int = 4) -> list[str]:
    return suggestions_for(user)[:limit]
